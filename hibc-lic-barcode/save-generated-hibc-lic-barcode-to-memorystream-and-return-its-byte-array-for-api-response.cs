// Title: Generate HIBC LIC barcode and return as byte array
// Description: Demonstrates creating a HIBC LIC QR barcode, saving it to a MemoryStream, and obtaining the raw byte array for use in API responses.
// Category-Description: This example belongs to the Aspose.BarCode barcode generation category, focusing on complex barcode types such as HIBC LIC. It shows how to configure primary data, adjust rendering parameters, and export the barcode image using ComplexBarcodeGenerator. Developers working with healthcare or logistics applications often need to produce HIBC‑compliant barcodes and return them as binary data for web APIs or other services.
// Prompt: Save the generated HIBC LIC barcode to a MemoryStream and return its byte array for an API response.
// Tags: hibc, lic, barcode, generation, memorystream, bytearray, aspnet, aspnetcore, aspnet-webapi, aspose.barcode

using System;
using System.IO;
using Aspose.BarCode;
using Aspose.BarCode.Generation;
using Aspose.BarCode.ComplexBarcode;

/// <summary>
/// Demonstrates generating a HIBC LIC barcode and retrieving its image as a byte array.
/// </summary>
class Program
{
    /// <summary>
    /// Entry point that creates the barcode, saves it to a MemoryStream, and outputs the byte array length and Base64 representation.
    /// </summary>
    static void Main()
    {
        // Prepare primary data for HIBC LIC barcode
        HIBCLICPrimaryDataCodetext codetext = new HIBCLICPrimaryDataCodetext();

        // Set the barcode type to HIBC QR LIC
        codetext.BarcodeType = EncodeTypes.HIBCQRLIC;

        // Populate the required fields of the primary data
        codetext.Data = new PrimaryData();
        codetext.Data.ProductOrCatalogNumber = "12345";
        codetext.Data.LabelerIdentificationCode = "A999";
        codetext.Data.UnitOfMeasureID = 1;

        byte[] barcodeBytes;

        // Use a MemoryStream to capture the generated barcode image
        using (MemoryStream ms = new MemoryStream())
        {
            // Initialize the complex barcode generator with the prepared codetext
            using (ComplexBarcodeGenerator gen = new ComplexBarcodeGenerator(codetext))
            {
                // Adjust rendering parameter: set X-dimension in pixels
                gen.Parameters.Barcode.XDimension.Pixels = 10;

                // Save the barcode image to the memory stream in PNG format
                gen.Save(ms, BarCodeImageFormat.Png);
            }

            // Convert the memory stream contents to a byte array
            barcodeBytes = ms.ToArray();
        }

        // Output the length of the generated byte array (for demonstration purposes)
        Console.WriteLine($"Generated barcode byte array length: {barcodeBytes.Length}");

        // Output the Base64 representation of the barcode image (for demonstration purposes)
        Console.WriteLine(Convert.ToBase64String(barcodeBytes));
    }
}