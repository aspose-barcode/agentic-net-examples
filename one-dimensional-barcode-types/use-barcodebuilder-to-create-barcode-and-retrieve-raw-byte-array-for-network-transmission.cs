// Title: Generate Code128 barcode and obtain raw PNG byte array
// Description: Demonstrates creating a Code128 barcode with Aspose.BarCode, saving it to a memory stream, and extracting the raw PNG bytes for transmission.
// Category-Description: This example belongs to the Aspose.BarCode barcode generation category. It showcases the use of BarcodeGenerator, EncodeTypes, and BarCodeImageFormat to produce barcodes in memory. Typical scenarios include embedding barcodes in network messages, APIs, or storing them in databases without writing to disk. Developers often need to retrieve the raw byte array for further processing or transmission.
// Prompt: Use BarCodeBuilder to create a barcode and retrieve the raw byte array for network transmission.
// Tags: barcode, code128, generation, png, byte-array, network, aspose.barcode, barcodgenerator

using System;
using System.IO;
using Aspose.BarCode;
using Aspose.BarCode.Generation;

/// <summary>
/// Provides an example of generating a barcode and extracting its byte representation.
/// </summary>
class Program
{
    /// <summary>
    /// Entry point that creates a Code128 barcode, saves it to a memory stream as PNG, and prints byte array details.
    /// </summary>
    /// <param name="args">Command‑line arguments (not used).</param>
    static void Main(string[] args)
    {
        // Define the text to encode in the barcode
        string codeText = "Sample123";

        // Initialize the barcode generator for Code128 symbology
        using (BarcodeGenerator generator = new BarcodeGenerator(EncodeTypes.Code128, codeText))
        {
            // Optionally adjust the module (X) dimension for higher resolution
            generator.Parameters.Barcode.XDimension.Pixels = 4f;

            // Create a memory stream to hold the generated image
            using (MemoryStream ms = new MemoryStream())
            {
                // Save the barcode as a PNG image into the memory stream
                generator.Save(ms, BarCodeImageFormat.Png);

                // Retrieve the raw PNG bytes from the stream
                byte[] barcodeBytes = ms.ToArray();

                // Display information about the generated byte array
                Console.WriteLine($"Generated barcode byte array length: {barcodeBytes.Length}");
                Console.WriteLine(BitConverter.ToString(barcodeBytes).Replace("-", " "));
            }
        }
    }
}