// Title: Generate Mailmark Barcode and Return Image Bytes
// Description: Demonstrates creating a Mailmark 4‑State barcode, saving it to a MemoryStream, and extracting the PNG image bytes for use in a web API.
// Category-Description: This example belongs to the Aspose.BarCode complex barcode generation category. It showcases the use of Aspose.BarCode.ComplexBarcode.ComplexBarcodeGenerator together with Aspose.BarCode.ComplexBarcode.MailmarkCodetext to produce Mailmark barcodes, a common requirement for postal services and logistics applications. Developers often need to generate barcode images in memory and return the raw bytes from web APIs, and this snippet illustrates the typical workflow using the key API classes.
// Prompt: Generate a Mailmark barcode into a MemoryStream and return image bytes to a web API.
// Tags: mailmark, barcode, generation, png, memorystream, aspnet, aspose.barcode, complexbarcode, image-bytes

using System;
using System.IO;
using Aspose.BarCode;
using Aspose.BarCode.ComplexBarcode;
using Aspose.BarCode.Generation;

/// <summary>
/// Example program that generates a Mailmark barcode and returns the image bytes.
/// </summary>
class Program
{
    /// <summary>
    /// Generates the barcode, writes it to a memory stream, and outputs the byte array length.
    /// </summary>
    static void Main()
    {
        // Define a sample Mailmark 4‑State codetext
        var mailmark = new MailmarkCodetext
        {
            Format = 4,
            VersionID = 1,
            Class = "0",
            SupplychainID = 384224,
            ItemID = 16563762,
            DestinationPostCodePlusDPS = "EF61AH8T "
        };

        // Create a memory stream to hold the generated PNG image
        using (var memoryStream = new MemoryStream())
        {
            // Initialize the complex barcode generator with the Mailmark codetext
            using (var generator = new ComplexBarcodeGenerator(mailmark))
            {
                // Set the X‑dimension (module size) in pixels
                generator.Parameters.Barcode.XDimension.Pixels = 4;

                // Save the barcode image to the memory stream in PNG format
                generator.Save(memoryStream, BarCodeImageFormat.Png);
            }

            // Reset the stream position to the beginning before reading
            memoryStream.Position = 0;

            // Convert the stream contents to a byte array
            byte[] imageBytes = memoryStream.ToArray();

            // Output the size of the generated byte array (for demonstration)
            Console.WriteLine($"Generated Mailmark barcode image bytes: {imageBytes.Length}");
        }
    }
}