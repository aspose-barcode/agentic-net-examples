// Title: Compare memory usage of ExportToXml with file path vs. stream
// Description: Demonstrates how to measure memory consumption when exporting a barcode configuration to XML using a file path (string) and a MemoryStream.
// Category-Description: This example belongs to the Aspose.BarCode generation category, showcasing the ExportToXml API for persisting barcode settings. It highlights typical use cases such as configuration backup, interoperability, and diagnostics, where developers need to understand the memory impact of different export targets. The example uses BarcodeGenerator, EncodeTypes, and QREncodeMode classes.
// Prompt: Compare memory usage of ExportToXml(Stream) versus ExportToXml(string) for identical configurations.
// Tags: qr, export, xml, memory, aspose.barcode, generation

using System;
using System.IO;
using System.Diagnostics;
using Aspose.BarCode;
using Aspose.BarCode.Generation;

/// <summary>
/// Provides an example that measures and compares the memory usage of
/// <see cref="BarcodeGenerator.ExportToXml(string)"/> and
/// <see cref="BarcodeGenerator.ExportToXml(Stream)"/> for the same barcode configuration.
/// </summary>
class Program
{
    /// <summary>
    /// Forces a full garbage collection and returns the current total managed memory.
    /// </summary>
    /// <returns>The total memory, in bytes, allocated by the managed heap.</returns>
    static long GetMemory()
    {
        GC.Collect();
        GC.WaitForPendingFinalizers();
        GC.Collect();
        return GC.GetTotalMemory(true);
    }

    /// <summary>
    /// Executes the memory‑usage comparison between the string‑based and stream‑based XML export methods.
    /// </summary>
    static void Main()
    {
        // Create a unique temporary folder to store the XML file generated by ExportToXml(string)
        string tempDir = Path.Combine(Path.GetTempPath(), "BarcodeXmlMem_" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempDir);
        string xmlFilePath = Path.Combine(tempDir, "generator.xml");

        // Initialize a barcode generator with a QR code and configure its parameters
        using (var generator = new BarcodeGenerator(EncodeTypes.QR, "SampleText"))
        {
            generator.Parameters.Barcode.XDimension.Pixels = 4;
            generator.Parameters.Barcode.QR.EncodeMode = QREncodeMode.Auto; // example additional setting

            // Measure memory before and after exporting to XML using a file path (string)
            long beforeString = GetMemory();
            generator.ExportToXml(xmlFilePath);
            long afterString = GetMemory();
            long diffString = afterString - beforeString;

            // Measure memory before and after exporting to XML using a MemoryStream
            using (var ms = new MemoryStream())
            {
                long beforeStream = GetMemory();
                generator.ExportToXml(ms);
                long afterStream = GetMemory();
                long diffStream = afterStream - beforeStream;

                // Output the memory differences for each export method
                Console.WriteLine($"Memory increase after ExportToXml(string): {diffString} bytes");
                Console.WriteLine($"Memory increase after ExportToXml(Stream): {diffStream} bytes");
            }
        }

        // Attempt to clean up the temporary directory and its contents
        try
        {
            Directory.Delete(tempDir, true);
        }
        catch
        {
            // Suppress any exceptions that occur during cleanup
        }
    }
}