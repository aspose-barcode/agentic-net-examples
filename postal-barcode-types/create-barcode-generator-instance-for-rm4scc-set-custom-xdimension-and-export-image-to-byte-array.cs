// Title: Generate RM4SCC Barcode and Export as PNG Byte Array
// Description: Demonstrates creating an RM4SCC barcode, customizing its X‑dimension, rendering it to a PNG image, and retrieving the image as a byte array.
// Category-Description: This example belongs to the Aspose.BarCode generation category, illustrating how to use the BarcodeGenerator class with EncodeTypes.RM4SCC, adjust barcode parameters such as XDimension, and export the generated image via Aspose.Drawing.Bitmap. Typical use cases include creating machine‑readable labels for logistics, inventory, or payment systems where RM4SCC is required. Developers often need to customize size, format, and obtain the image data for further processing or storage.
// Prompt: Create a barcode generator instance for RM4SCC, set custom XDimension, and export image to a byte array.
// Tags: rm4scc,barcode,generation,xdimension,bytearray,png,aspose.barcode,aspose.drawing

using System;
using System.IO;
using Aspose.BarCode;
using Aspose.BarCode.Generation;
using Aspose.Drawing;
using Aspose.Drawing.Imaging;

/// <summary>
/// Example program that generates an RM4SCC barcode, customizes its X-dimension,
/// and exports the resulting PNG image to a byte array.
/// </summary>
class Program
{
    /// <summary>
    /// Entry point of the example. Generates the barcode and writes the byte array length to the console.
    /// </summary>
    static void Main()
    {
        // The text to encode in the barcode.
        string codeText = "123456ASPOSE";

        // Create a barcode generator for the RM4SCC symbology with the specified text.
        using (BarcodeGenerator generator = new BarcodeGenerator(EncodeTypes.RM4SCC, codeText))
        {
            // Set a custom X-dimension (module width) in pixels.
            generator.Parameters.Barcode.XDimension.Pixels = 3f;

            // Generate the barcode image as a Bitmap.
            using (Bitmap bitmap = generator.GenerateBarCodeImage())
            {
                // Save the bitmap to a memory stream in PNG format.
                using (MemoryStream ms = new MemoryStream())
                {
                    bitmap.Save(ms, ImageFormat.Png);

                    // Convert the memory stream to a byte array.
                    byte[] barcodeBytes = ms.ToArray();

                    // Output the length of the generated byte array.
                    Console.WriteLine($"Barcode byte array length: {barcodeBytes.Length}");
                }
            }
        }
    }
}