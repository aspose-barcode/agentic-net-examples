using System;
using System.IO;
using System.Text;
using Aspose.BarCode;
using Aspose.BarCode.Generation;

/// <summary>
/// Provides an example of generating a DataMatrix barcode and obtaining its image as a byte array.
/// </summary>
class Program
{
    /// <summary>
    /// Entry point of the example. Generates a DataMatrix barcode, displays its size, and saves the image to a file.
    /// </summary>
    static void Main()
    {
        // Text to encode in the DataMatrix barcode
        string sampleText = "Aspose DataMatrix";

        // Generate the barcode and obtain the PNG image as a byte array
        byte[] barcodeBytes = GenerateDataMatrixBarcode(sampleText);

        // Output the length of the generated byte array for verification
        Console.WriteLine($"Generated DataMatrix barcode byte array length: {barcodeBytes.Length}");

        // Define the output file path and write the byte array to a PNG file
        string outputPath = Path.Combine(Directory.GetCurrentDirectory(), "DataMatrix.png");
        File.WriteAllBytes(outputPath, barcodeBytes);
        Console.WriteLine($"Saved barcode image to {outputPath}");
    }

    /// <summary>
    /// Generates a DataMatrix barcode image in PNG format and returns the image bytes.
    /// </summary>
    /// <param name="codeText">The text to encode in the barcode.</param>
    /// <returns>Byte array containing the PNG image of the generated barcode.</returns>
    static byte[] GenerateDataMatrixBarcode(string codeText)
    {
        // Initialize the barcode generator for DataMatrix symbology
        using (var generator = new BarcodeGenerator(EncodeTypes.DataMatrix))
        {
            // Set the size of each module (pixel) in the barcode
            generator.Parameters.Barcode.XDimension.Pixels = 8f;

            // Assign the text to encode, using UTF-8 encoding
            generator.SetCodeText(codeText, Encoding.UTF8);

            // Save the barcode image to a memory stream in PNG format
            using (var ms = new MemoryStream())
            {
                generator.Save(ms, BarCodeImageFormat.Png);
                // Return the image as a byte array
                return ms.ToArray();
            }
        }
    }
}