// Title: Generate MaxiCode barcode and return as byte array
// Description: Creates a MaxiCode barcode, saves it to a MemoryStream in PNG format, and returns the resulting byte array.
// Category-Description: This example demonstrates Aspose.BarCode barcode generation for the MaxiCode symbology. It uses the BarcodeGenerator class to configure encoding parameters, renders the barcode to a MemoryStream, and extracts the image bytes. Typical scenarios include generating shipping labels, inventory tags, or any application that requires MaxiCode images without writing to disk. Developers working with barcode creation often need to output images directly to streams for web APIs, databases, or further processing.
// Prompt: Save generated MaxiCode barcode to a MemoryStream and return the byte array to the caller.
// Tags: maxicode, barcode generation, memorystream, byte array, aspose.barcode, png, encoding

using System;
using System.IO;
using Aspose.BarCode;
using Aspose.BarCode.Generation;
using Aspose.Drawing;

/// <summary>
/// Demonstrates how to generate a MaxiCode barcode, store it in a MemoryStream,
/// and return the image as a byte array.
/// </summary>
class Program
{
    /// <summary>
    /// Entry point of the example. Calls the barcode generation method and writes the result length to the console.
    /// </summary>
    static void Main()
    {
        // Generate the barcode and obtain the PNG image bytes
        byte[] barcodeBytes = GenerateMaxiCodeBarcode();

        // Output the size of the generated byte array for verification
        Console.WriteLine($"Generated MaxiCode barcode byte array length: {barcodeBytes.Length}");
    }

    /// <summary>
    /// Generates a MaxiCode barcode with sample text, saves it to a MemoryStream in PNG format,
    /// and returns the resulting byte array.
    /// </summary>
    /// <returns>Byte array containing the PNG image of the generated MaxiCode barcode.</returns>
    static byte[] GenerateMaxiCodeBarcode()
    {
        // Text to encode in the MaxiCode barcode
        string codeText = "Sample MaxiCode";

        // Initialize the barcode generator for MaxiCode symbology
        using (var generator = new BarcodeGenerator(EncodeTypes.MaxiCode, codeText))
        {
            // Configure MaxiCode mode to Mode4 (arbitrary text encoding)
            generator.Parameters.Barcode.MaxiCode.Mode = MaxiCodeMode.Mode4;

            // Optional: adjust the size of each module (pixel dimension)
            generator.Parameters.Barcode.XDimension.Pixels = 15f;

            // Create a memory stream to hold the generated image
            using (var memoryStream = new MemoryStream())
            {
                // Save the barcode image to the stream in PNG format
                generator.Save(memoryStream, BarCodeImageFormat.Png);

                // Return the image data as a byte array
                return memoryStream.ToArray();
            }
        }
    }
}