using System;
using System.IO;
using Aspose.BarCode;
using Aspose.BarCode.Generation;
using Aspose.Drawing;
using Aspose.Slides;
using Aspose.Slides.Export;

/// <summary>
/// Example program that generates a QR Code barcode and embeds it into a PowerPoint slide.
/// </summary>
class Program
{
    /// <summary>
    /// Entry point of the application.
    /// Generates a QR Code, adds it to a new presentation, and saves the file.
    /// </summary>
    static void Main()
    {
        // Define the text to encode in the QR Code.
        const string qrText = "Sample QR Code generated by Aspose.BarCode";

        // Initialize the barcode generator for QR encoding.
        using (BarcodeGenerator generator = new BarcodeGenerator(EncodeTypes.QR, qrText))
        {
            // Set the size of each QR module (optional).
            generator.Parameters.Barcode.XDimension.Point = 2f;

            // Set the error correction level to Medium (optional).
            generator.Parameters.Barcode.QR.ErrorLevel = QRErrorLevel.LevelM;

            // Render the barcode to a memory stream in PNG format.
            using (MemoryStream barcodeStream = new MemoryStream())
            {
                generator.Save(barcodeStream, BarCodeImageFormat.Png);
                barcodeStream.Position = 0; // Reset stream position for reading.

                // Create a new PowerPoint presentation.
                using (Presentation presentation = new Presentation())
                {
                    // Add the PNG image to the presentation's image collection.
                    IPPImage pptImage = presentation.Images.AddImage(barcodeStream);

                    // Retrieve the first (default) slide.
                    ISlide slide = presentation.Slides[0];

                    // Insert the image onto the slide as a picture frame.
                    // Coordinates and size are specified in points.
                    slide.Shapes.AddPictureFrame(ShapeType.Rectangle, 50, 50, 300, 300, pptImage);

                    // Define the output file path in the temporary folder.
                    string outputPath = Path.Combine(Path.GetTempPath(), "QrCodePresentation.pptx");

                    // Save the presentation to disk in PPTX format.
                    presentation.Save(outputPath, SaveFormat.Pptx);

                    // Inform the user where the file was saved.
                    Console.WriteLine($"Presentation saved to: {outputPath}");
                }
            }
        }
    }
}